    interface Plot {
        void plot(int x, int y, int rgb);
    }

    private HostFont() {
    }

    static int height() {
        return CELL;
    }

    static int width(String s) {
        if (s == null || s.isEmpty()) {
            return 0;
        }
        int max = 0;
        int n = 0;
        for (int i = 0; i < s.length(); i++) {
            if (s.charAt(i) == '\n') {
                max = Math.max(max, n);
                n = 0;
            } else {
                n++;
            }
        }
        return Math.max(max, n) * CELL;
    }

    static int pixelCount(char ch) {
        int[] glyph = glyph(ch);
        int n = 0;
        for (int row : glyph) {
            n += Integer.bitCount(row & 0xFF);
        }
        return n;
    }

    static void draw(String s, int x, int y, int rgb, Plot plot) {
        if (s == null || s.isEmpty() || plot == null) {
            return;
        }
        int cx = x;
        int cy = y;
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            if (ch == '\n') {
                cx = x;
                cy += CELL + SCALE;
                continue;
            }
            int[] glyph = glyph(ch);
            for (int row = 0; row < 8; row++) {
                int bits = glyph[row] & 0xFF;
                for (int col = 0; col < 8; col++) {
                    if ((bits & 0x80) != 0) {
                        for (int dy = 0; dy < SCALE; dy++) {
                            for (int dx = 0; dx < SCALE; dx++) {
                                plot.plot(cx + col * SCALE + dx, cy + row * SCALE + dy, rgb);
                            }
                        }
                    }
                    bits = (bits << 1) & 0xFF;
                }
            }
            cx += CELL;
        }
    }

    private static int[] glyph(char ch) {
        int code = ch;
        if (code < 32 || code > 126) {
            code = '?';
        }
        return GLYPHS[code - 32];
    }
